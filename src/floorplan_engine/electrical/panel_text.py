def text(key: str, language: Language, **kw: object) -> str:
    return TEXT[key][language].format(**kw)


def kw(watts: float) -> str:
    """W → "1,25" kW."""
    return f"{watts / 1000:.2f}".replace(".", ",")


def amps(value: float) -> str:
    return f"{value:.1f}".replace(".", ",")
